import { useEffect, useState } from 'react';
import { Icon } from './Common.jsx';
import { EditText } from './Editable.jsx';
import { ACCOUNT_MAX } from '../../../shared/account.js';

// "Get the app" card at the bottom of the side navigation (Campaigns section). Its QR code is
// made from the app link an admin adds (account detail appUrl); read-only users see the card
// only once there is a link. Admins edit the title, text and link on the card itself.
// Collapse folds it to its header; Close hides it until this browser tab's session ends.

const CLOSED_KEY = 'ap.appCard.closed';
const FOLDED_KEY = 'ap.appCard.folded';
const readFlag = (key) => {
  try { return sessionStorage.getItem(key) === '1'; } catch { return false; }
};
const writeFlag = (key, on) => {
  try {
    if (on) sessionStorage.setItem(key, '1');
    else sessionStorage.removeItem(key);
  } catch { /* storage off: the choice lasts until the page reloads */ }
};
const openHelp = () => window.dispatchEvent(new CustomEvent('app:help', { detail: { topic: 'app-card' } }));

// The QR code of a link, drawn by the qrcode library (loaded on first use). Its SVG markup is
// generated by the library from the link's bits; the link itself is never inserted as markup.
function QrCode({ url }) {
  const [svg, setSvg] = useState('');
  useEffect(() => {
    let live = true;
    setSvg('');
    import('qrcode')
      .then((m) => (m.default || m).toString(url, { type: 'svg', margin: 0, errorCorrectionLevel: 'M' }))
      .then((s) => { if (live && typeof s === 'string' && s.startsWith('<svg ')) setSvg(s); })
      .catch(() => { if (live) setSvg(''); });
    return () => { live = false; };
  }, [url]);
  return (
    <a className="qr" href={url} target="_blank" rel="noopener noreferrer" aria-label="App link QR code (opens the link)"
      data-testid="app-qr" data-ready={svg ? 'true' : 'false'} dangerouslySetInnerHTML={{ __html: svg }} />
  );
}

export default function AppCard({ account, canEdit, onAccount }) {
  const [closed, setClosed] = useState(() => readFlag(CLOSED_KEY));
  const [folded, setFolded] = useState(() => readFlag(FOLDED_KEY));
  // The server only stores https links; anything else is treated as no link.
  const url = /^https:\/\//i.test(account.appUrl || '') ? account.appUrl : '';
  if (closed || (!url && !canEdit)) return null;
  const close = () => { writeFlag(CLOSED_KEY, true); setClosed(true); };
  const fold = () => setFolded((f) => { writeFlag(FOLDED_KEY, !f); return !f; });
  const saveUrl = (v) => onAccount('appUrl', v.trim());
  return (
    <section className={`app-card ${folded ? 'folded' : ''}`} aria-label="App card" data-testid="app-card">
      <div className="app-card-head">
        <Icon name="system_update" />
        <span className="acard-title" data-testid="app-card-title">
          <EditText value={account.appTitle} canEdit={canEdit} maxLength={ACCOUNT_MAX.appTitle} label="app card title" onSave={(v) => onAccount('appTitle', v)} />
        </span>
        <button type="button" className="iconbtn sm" aria-label={folded ? 'Expand' : 'Collapse'} title={folded ? 'Expand' : 'Collapse'}
          aria-expanded={!folded} data-testid="app-card-fold" onClick={fold}>
          <Icon name={folded ? 'unfold_more' : 'unfold_less'} />
        </button>
        <button type="button" className="iconbtn sm" aria-label="Close" title="Hide for this session" data-testid="app-card-close" onClick={close}>
          <Icon name="close" />
        </button>
      </div>
      {!folded && (url ? (
        <div className="app-card-body" data-testid="app-card-body">
          <QrCode url={url} />
          <div className="acard-text">
            <span data-testid="app-card-text">
              <EditText value={account.appText} canEdit={canEdit} maxLength={ACCOUNT_MAX.appText} label="app card text" onSave={(v) => onAccount('appText', v)} />
            </span>
            <span className="acard-links">
              <a href={url} target="_blank" rel="noopener noreferrer" data-testid="app-open-link">Open link</a>
              {canEdit && (
                <EditText value={url} canEdit clickToEdit maxLength={ACCOUNT_MAX.appUrl} label="app link" placeholder="https://" onSave={saveUrl}>
                  <span className="acard-change">Change link</span>
                </EditText>
              )}
            </span>
          </div>
        </div>
      ) : (
        <div className="app-card-body no-link" data-testid="app-card-body">
          <span className="acard-noqr" aria-hidden="true"><Icon name="qr_code_2" /></span>
          <div className="acard-text">
            <EditText value="" canEdit clickToEdit maxLength={ACCOUNT_MAX.appUrl} label="app link" placeholder="https://" onSave={saveUrl}>
              <span className="acard-add">Add your app link</span>
            </EditText>
            <span className="acard-note">
              Its QR code shows here. Read-only users see this card once a link is added.
              <button type="button" className="acard-learn" onClick={openHelp}>Learn more</button>
            </span>
          </div>
        </div>
      ))}
    </section>
  );
}
